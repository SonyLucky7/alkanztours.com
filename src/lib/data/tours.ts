// ── Helper Functions ────────────────────────────────────────

export function getTourBySlug(slug: string): Tour | undefined {
  return tours.find((t) => t.slug === slug);
}

export function getToursByCategory(category: Category): Tour[] {
  return tours.filter((t) => t.category === category);
}

export function getToursByDestination(destination: Destination): Tour[] {
  return tours.filter((t) => t.destination === destination);
}

export function getFeaturedTours(): Tour[] {
  return tours.filter((t) => t.featured);
}

export function getRelatedTours(tour: Tour, limit = 4): Tour[] {
  return tours
    .filter((t) => t.id !== tour.id && t.category === tour.category)
    .slice(0, limit);
}

export function searchTours(query: string): Tour[] {
  const q = query.toLowerCase().trim();
  if (!q) return tours;
  return tours.filter(
    (t) =>
      t.name.toLowerCase().includes(q) ||
      t.description.toLowerCase().includes(q) ||
      t.categoryLabel.toLowerCase().includes(q) ||
      t.destinationLabel.toLowerCase().includes(q) ||
      t.tags.some((tag) => tag.toLowerCase().includes(q))
  );
}

export function formatPrice(price: number, currency = 'AED'): string {
  const formatted = price % 1 === 0 ? price.toString() : price.toFixed(2);
  return `${currency} ${formatted}`;
}

export function getAllCategories(): Array<{ value: Category; label: string; count: number }> {
  return (Object.entries(categories) as [Category, typeof categories[Category]][]).map(
    ([value, data]) => ({
      value,
      label: data.label,
      count: data.count ?? 0,
    })
  );
}

export function getAllDestinations(): Array<{ value: Destination; label: string }> {
  return (Object.entries(destinations) as [Destination, typeof destinations[Destination]][]).map(
    ([value, data]) => ({
      value,
      label: data.label,
    })
  );
}
