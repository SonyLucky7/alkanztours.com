// Helper to determine destination from category
function getDestination(category: Category, name: string): Destination {
  if (category === 'abu-dhabi-attractions') return 'abu-dhabi';
  if (category === 'musandam-tours') return 'musandam';
  if (name.toLowerCase().includes('fujairah')) return 'fujairah';
  if (name.toLowerCase().includes('abu dhabi') || name.toLowerCase().includes('yas ')) return 'abu-dhabi';
  if (name.toLowerCase().includes('musandam')) return 'musandam';
  return 'dubai';
}

function getDestinationLabel(dest: Destination): string {
  return destinations[dest].label;
}

function getCategoryLabel(cat: Category): string {
  return categories[cat].label;
}

